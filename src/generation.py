from transformers import AutoModelForCausalLM, AutoTokenizer
from src.models import MinimalSource
from src.errors import (FileReadError,
                        GenerationError, InvalidQueryError)
from src.files import read_span
from typing import List, Any


MAX_NEW_TOKENS = 100
NO_INFO_ANSWER = "I do not have enough information to answer the question."


class Generator:
    """
    Generate answers with a local language model.
    The model is loaded once, when the object is created.
    """
    def __init__(self, model_name: str = "Qwen/Qwen3-0.6B") -> None:
        try:
            self.tokenizer = AutoTokenizer.from_pretrained(model_name)
            self.model: Any = AutoModelForCausalLM.from_pretrained(
                model_name)
        except (OSError, ValueError) as e:
            raise GenerationError(
                f"cannot load the model {model_name}: {e}") from e

    def build_prompt(self, question: str, contexts: List[str]) -> str:
        """
        Build the text sent to the model.

        Args:
            question: The question to answer.
            contexts: Text of each retrieved source.

        Returns:
            The prompt, ready for the chat template.
        """
        numbered = "\n".join(
            f"[{i}] {text}" for i, text in enumerate(contexts, start=1))
        return (
           f"Context:\n{numbered}\n\n"
           f"Question: {question}")

    def answer(self, question: str, sources: List[MinimalSource],
               k: int) -> str:
        """
        Answer a question using the text of the given sources.

        Args:
            question: The question to answer.
            sources: Retrieved sources, best first.
            k: How many sources to give to the model.

        Returns:
            The answer generated by the model.
        """
        if not question.strip():
            raise InvalidQueryError("the question is empty")
        context: List[str] = []
        for s in sources[:k]:
            try:
                context.append(read_span(s))
            except FileReadError:
                continue
        if not context:
            return NO_INFO_ANSWER
        system_prompt = (
           "Answer the question using ONLY the given context. "
           "Never use your own knowledge. Answer in at most two sentences. "
           "In case the context does not contain the answer,"
           f" reply with exactly: '{NO_INFO_ANSWER}'\n\n")
        prompt = self.build_prompt(question, context)
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt}]
        text = self.tokenizer.apply_chat_template(
            messages, tokenize=False,
            add_generation_prompt=True, enable_thinking=False)
        inputs = self.tokenizer(text, return_tensors="pt")
        try:
            output = self.model.generate(**inputs,
                                         max_new_tokens=MAX_NEW_TOKENS,
                                         do_sample=False)
        except RuntimeError as e:
            raise GenerationError(f"the model failed: {e}") from e
        new_tokens = output[0][inputs["input_ids"].shape[1]:]
        answer = self.tokenizer.decode(new_tokens, skip_special_tokens=True)
        if not isinstance(answer, str):
            raise GenerationError("Unexpected tokenizer output")
        return answer.strip()
